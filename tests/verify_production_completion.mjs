import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const exists=(p)=>fs.existsSync(path.join(root,p));
const checks=[];
function check(name,ok){checks.push([name,!!ok]); if(!ok) console.error('FAIL',name)}
check('AEAT provider exists',exists('apps/api/src/modules/billing/verifactu/provider.ts'));
check('AEAT XML builder exists',exists('apps/api/src/modules/billing/verifactu/xml-builder.ts'));
