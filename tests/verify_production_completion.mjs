check('cost recipe service exists',exists('apps/api/src/modules/analytics/cost-recipes.ts'));
check('cost recipe routes',/cost-recipes/.test(read('apps/api/src/modules/analytics/routes.ts')));
check('treatment completion snapshots recipe cost',/resolveStandardTreatmentCost/.test(read('apps/api/src/modules/clinical/service.ts')));
check('advanced alternatives',/toothPrognosisAlternatives/.test(read('packages/domain/src/treatment-plan/index.ts')) && /kennedy/.test(read('packages/domain/src/treatment-plan/index.ts')));
check('voice executes payments',/case\s*"payment\.record"/.test(read('apps/api/src/modules/voice/service.ts')) && /recordPaymentTx/.test(read('apps/api/src/modules/voice/service.ts')));
check('voice executes lab transitions',/case\s*"lab\.transition"/.test(read('apps/api/src/modules/voice/service.ts')) && /transitionLabWorkTx/.test(read('apps/api/src/modules/voice/service.ts')));
check('document template versioning',/createTemplateVersion/.test(read('apps/api/src/modules/documents/service.ts')));
